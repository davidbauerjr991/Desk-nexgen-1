// ─── Types ────────────────────────────────────────────────────────────────────

export type Channel = "chat" | "sms" | "email" | "voice" | "whatsapp";
export type Priority = "Critical" | "High" | "Medium" | "Low";
export type QueueAssignmentStatus = "open" | "pending" | "escalated" | "resolved" | "parked";

export interface AiOverview {
  actions: string[];
  whyNeeded: string;
  nextSteps: string[];
}

export interface LeadIntelligenceData {
  formMessage: string;
  browsedPages: Array<{ page: string; timeSpent?: string }>;
  company: string;
  location: string;
  formAnswer: string;
  openingLines: Array<{ intro: string; question: string }>;
  /** Aria's narrative summary shown in the Case Overview accordion card. */
  ariaMessage?: string;
  /** AI confidence score (0–100) shown as a percentage bar. */
  aiConfidence?: number;
  /** Human-readable explanation shown beneath the confidence bar. */
  aiConfidenceReason?: string;
}

export type CaseType =
  | "Billing Dispute"
  | "Payment Issue"
  | "Account Locked"
  | "Security Alert"
  | "Service Outage"
  | "Identity Verification"
  | "Compliance Request"
  | "Contract & Renewal"
  | "Technical Error"
  | "Incorrect AI Guidance"
  | "Subscription Upgrade"
  | "Scheduling"
  | "General Inquiry"
  | "IT Support"
  | "Order Issue"
  | "Sales Lead"
  | "Cross-Sell Opportunity"
  | "Flight Disruption"
  | "Rebooking Request"
  | "Accommodation Request"
  | "Baggage Issue"
  | "Refund Request"
  | "Compensation Claim";

export interface StaticAssignment {
  id: string;
  name: string;
  customerId: string;
  customerRecordId?: string;
  company: string;
  /** The type of AI bot or human agent that was servicing this case */
  botType: string;
  /** Categorised case type for grouping and filtering */
  caseType: CaseType;
  /** Whether this case was being handled by a virtual bot or a human agent */
  agentType: "virtual" | "human";
  channel: Channel;
  priority: Priority;
  status: QueueAssignmentStatus;
  preview: string;
  waitTime: string;
  /** Brief customer profile context for the agent: tenure, history, sentiment */
  customerContext: string;
  aiOverview: AiOverview;
  /**
   * When set, the escalation toast shows the AI Confidence meter and Approve button.
   * Represents the AI's confidence (0–100) that the requested action is correct.
   */
  aiConfidence?: number;
  /** Human-readable explanation shown beneath the confidence bar. */
  aiConfidenceReason?: string;
  /**
   * The agent this case is currently assigned to.
   * null = unassigned (waiting in queue).
   * Set when an agent clicks Takeover; cleared when they transfer or dismiss.
   */
  assignedTo: string | null;
  /** Present only for Sales Lead cases — surface AI-gathered intelligence for the incoming callback. */
  leadIntelligence?: LeadIntelligenceData;
}

